import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import { renderHook, act } from '@testing-library/react'
import { useReplay, REPLAY_MS } from './useReplay'

beforeEach(() => vi.useFakeTimers())
afterEach(() => vi.useRealTimers())
const tick = (n = 1) => act(() => { vi.advanceTimersByTime(REPLAY_MS * n) })

describe('useReplay', () => {
  it('starts on the last round, paused, and cadence is 520ms', () => {
    const { result } = renderHook(() => useReplay(5))
    expect(REPLAY_MS).toBe(520)
    expect(result.current).toMatchObject({ round: 5, playing: false, source: 'seek', atEnd: true })
  })
  it('play from the end restarts at round 1, advances one round per tick and stops at the end', () => {
    const { result } = renderHook(() => useReplay(4))
    act(() => result.current.toggle())
    expect(result.current).toMatchObject({ round: 1, playing: true, source: 'play' })
    tick()
    expect(result.current.round).toBe(2)
    tick()
    expect(result.current.round).toBe(3)
    tick()
    expect(result.current).toMatchObject({ round: 4, playing: false, atEnd: true, source: 'play' })
    tick(3)
    expect(result.current.round).toBe(4)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('pause keeps the round; play resumes from it', () => {
    const { result } = renderHook(() => useReplay(6))
    act(() => result.current.seek(2))
    act(() => result.current.toggle())
    tick()
    expect(result.current.round).toBe(3)
    act(() => result.current.toggle())
    expect(result.current.playing).toBe(false)
    tick(3)
    expect(result.current.round).toBe(3)
    act(() => result.current.toggle())
    tick()
    expect(result.current.round).toBe(4)
  })
  it('seeking pauses playback, marks the move as a seek and clamps', () => {
    const { result } = renderHook(() => useReplay(5))
    act(() => result.current.toggle())
    act(() => result.current.seek(3))
    expect(result.current).toMatchObject({ round: 3, playing: false, source: 'seek' })
    act(() => result.current.seek(99))
    expect(result.current.round).toBe(5)
    act(() => result.current.seek(-4))
    expect(result.current.round).toBe(1)
    act(() => result.current.seek(NaN))
    expect(result.current.round).toBe(1)
    act(() => result.current.seek(2.7))
    expect(result.current.round).toBe(2)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('reset returns to the last round, paused', () => {
    const { result } = renderHook(() => useReplay(5))
    act(() => result.current.toggle())
    tick()
    act(() => result.current.reset())
    expect(result.current).toMatchObject({ round: 5, playing: false, source: 'seek' })
    expect(vi.getTimerCount()).toBe(0)
  })
  it('a season or view change resets and clears the interval (no leaked timers)', () => {
    const { result, rerender } = renderHook(({ k, n }) => useReplay(n, k), { initialProps: { k: 'a', n: 5 } })
    act(() => result.current.toggle())
    tick()
    expect(vi.getTimerCount()).toBe(1)
    rerender({ k: 'b', n: 5 })
    expect(result.current).toMatchObject({ round: 5, playing: false })
    expect(vi.getTimerCount()).toBe(0)
    act(() => result.current.toggle())
    tick()
    rerender({ k: 'b', n: 8 })
    expect(result.current).toMatchObject({ round: 8, playing: false })
    expect(vi.getTimerCount()).toBe(0)
  })
  it('unmount clears the interval', () => {
    const { result, unmount } = renderHook(() => useReplay(5))
    act(() => result.current.toggle())
    expect(vi.getTimerCount()).toBe(1)
    unmount()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('one round or none: play is a no-op', () => {
    const one = renderHook(() => useReplay(1))
    act(() => one.result.current.toggle())
    expect(one.result.current).toMatchObject({ round: 1, playing: false })
    const none = renderHook(() => useReplay(0))
    act(() => none.result.current.toggle())
    expect(none.result.current.round).toBe(1)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('after a dataset change no tick from the old dataset arrives', () => {
    const { result, rerender } = renderHook(({ k }) => useReplay(5, k), { initialProps: { k: 'a' } })
    act(() => result.current.toggle())
    rerender({ k: 'b' })
    tick(2)
    expect(result.current.round).toBe(5)
  })
})
